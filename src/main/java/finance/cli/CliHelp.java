package finance.cli;

final class CliHelp {
    private static final String GENERAL_COMMANDS = """
            Учётная запись
              register <логин>  Создать учётную запись, например register anna
              login <логин>     Войти или сменить пользователя, например login anna
              Пароль вводится отдельной строкой после запроса. Логин вводится без пробелов.

            Общие команды
              help              Показать справку
              exit              Сохранить изменения и завершить приложение
            """;

    private static final String WALLET_COMMANDS = """

            Текущий сеанс
              whoami            Показать текущий логин
              logout            Выйти из учётной записи

            Операции и бюджеты
              income <сумма> <категория>         Например income 60000 Зарплата
              expense <сумма> <категория>        Например expense 250,50 Коммунальные услуги
              transfer <сумма> <логин>          Например transfer 250 boris
              balance                            Показать баланс
              history                            Показать историю
              category <название>                Например category Коммунальные услуги
              categories                         Показать категории, расходы и лимиты
              category-rename <старое>, <новое>  Например category-rename Еда, Продукты
              budget <сумма> <категория>         Например budget 3000 Коммунальные услуги
              budget-change <сумма> <категория>  Например budget-change 3500 Коммунальные услуги
              budget-remove <категория>          Например budget-remove Коммунальные услуги
              В суммах используйте точку или запятую и до двух знаков после неё.
              Одиночное название в конце команды вводится целиком, без кавычек.
              Перевод возможен зарегистрированному пользователю в пределах вашего баланса.

            Отчёты
              report [категории]                         Например report Еда, Коммунальные услуги
              report-period <с> <по> [категории]           Например report-period 2026-11-01 2026-11-30 Еда
              report-file [категории]                    Сохранить сводку в текстовый файл
              report-file-period <с> <по> [категории]    Сохранить отчёт за период
              Даты вводятся в формате ГГГГ-ММ-ДД. Обе границы включаются.
              В списках и при переименовании разделяйте названия запятыми.
              Названия с запятыми или кавычками заключайте в двойные кавычки,
              внутренние кавычки удваивайте. Например report "Еда, кафе", "Премия ""зима"" за год"
              Путь для текстового отчёта вводится отдельной строкой после запроса.

            Снимки кошелька
              export-csv <путь>   Например export-csv Мой кошелёк.csv
              import-csv <путь>   Например import-csv Мой кошелёк.csv
              Путь с пробелами вводится целиком, без кавычек.
              Для замены текущего кошелька при импорте введите yes после запроса.
            """;

    private CliHelp() {
    }

    static String text(boolean loggedIn) {
        return GENERAL_COMMANDS + (loggedIn ? WALLET_COMMANDS : "\nВойдите, чтобы увидеть команды кошелька.\n");
    }
}
